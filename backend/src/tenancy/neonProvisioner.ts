import { env } from '../config/env.js';

type NeonDatabase = { id?: string; name?: string; owner_name?: string };

function requireNeonConfig() {
  if (!env.NEON_API_KEY || !env.NEON_PROJECT_ID || !env.NEON_BRANCH_ID) {
    throw new Error('Tenant database provisioning requires NEON_API_KEY, NEON_PROJECT_ID, and NEON_BRANCH_ID.');
  }
  if (!env.TENANT_CONNECTION_BASE_URL) {
    throw new Error('TENANT_CONNECTION_BASE_URL is required to connect to tenant databases.');
  }
}

/**
 * Creates a Neon database using the Neon API. Check the current Neon API docs
 * and project permissions before production use. The name is generated by our
 * server and restricted to safe characters.
 */
export async function createTenantDatabase(databaseName: string): Promise<void> {
  requireNeonConfig();
  if (!/^[a-z][a-z0-9_]{2,62}$/.test(databaseName)) {
    throw new Error('Unsafe tenant database name.');
  }

  const response = await fetch(
    `https://console.neon.tech/api/v2/projects/${env.NEON_PROJECT_ID}/branches/${env.NEON_BRANCH_ID}/databases`,
    {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${env.NEON_API_KEY}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        database: { name: databaseName, owner_name: env.NEON_DATABASE_OWNER || undefined }
      })
    }
  );

  if (!response.ok) {
    const body = await response.text();
    throw new Error(`Neon database provisioning failed (${response.status}): ${body.slice(0, 500)}`);
  }
  await response.json() as { database?: NeonDatabase };
}

export function tenantConnectionString(databaseName: string): string {
  if (!env.TENANT_CONNECTION_BASE_URL) throw new Error('TENANT_CONNECTION_BASE_URL is not configured.');
  const url = new URL(env.TENANT_CONNECTION_BASE_URL);
  url.pathname = `/${databaseName}`;
  if (!url.searchParams.has('sslmode')) url.searchParams.set('sslmode', 'require');
  return url.toString();
}
